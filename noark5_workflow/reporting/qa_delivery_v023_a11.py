"""Read-only bridge from a9/a10 DWM delivery findings to established KS/A260.

A depot report binds a separate, COMPLETE JSONL register generated by the
DWM XML validation job. Do not replace individual occurrences with the
aggregate deviations stored in the report. Keep review keys stable and unique
per occurrence. No Source reads, new test decisions or approval writes.

Small records are available directly to the existing append-only a13 review
API. Large records are verified to EOF and given an explicitly partial preview;
A260 consumes the full source stream, and page-wise GUI review follows in a12.
"""
from __future__ import annotations

from collections import Counter
from hashlib import sha256
import json
from pathlib import Path
import re
from typing import Iterator


MODEL_IDS = frozenset((
    'dwm.noark5.delivery-validation.a9.v1',
    'dwm.noark5.delivery-validation.a10.v1',
))
VERSIONS = frozenset(('3.1', '4.0', '5.0'))
DELIVERY_SOURCES = frozenset(('DWM avleveringskontroll', 'DWM periodekonsistens'))
AGGREGATE_CATEGORIES = frozenset({
    'delivery_value_M051', 'delivery_value_M052',
    'delivery_value_M053', 'delivery_value_M054',
    'delivery_period_chronology',
})
PREVIEW_LIMIT = 250  # Only the existing KS GUI; not a finding/capacity ceiling.
MAX_FINDING_LINE_BYTES = 24 * 1024 * 1024  # Reject impossible token, never truncate.
_SHA = re.compile(r'[a-f0-9]{64}\Z')
_REQUIRED = ('source', 'test_id', 'severity', 'message', 'context', 'file',
             'lines', 'source_ref', 'finding_uid', 'metadata_id', 'xpath',
             'object_id', 'archive_part_id')


class DeliveryQaError(ValueError):
    """An invalid or altered DWM delivery source must never be presented as complete."""


def _hash(path: Path) -> str:
    h = sha256()
    with path.open('rb') as stream:
        for data in iter(lambda: stream.read(1024 * 1024), b''):
            h.update(data)
    return h.hexdigest()


def _safe_work_file(root: Path, relative: str) -> Path:
    """No absolute paths, Windows drives, traversal, or symlinked components."""
    if (not isinstance(relative, str) or not relative or relative.startswith('/')
            or '\\' in relative or '\x00' in relative or ':' in relative.split('/')[0]):
        raise DeliveryQaError('DWM-evidens krever sikker Work-relativ filsti')
    components = relative.split('/')
    if any(c in ('', '.', '..') for c in components):
        raise DeliveryQaError('Utrygg DWM-evidenssti')
    target = root
    for part in components:
        target = target / part
        if target.is_symlink():
            raise DeliveryQaError('Symbolsk lenke i DWM-evidenssti')
    if not target.resolve(strict=False).is_relative_to(root.resolve(strict=True)):
        raise DeliveryQaError('DWM-evidens utenfor valgt Work')
    if not target.is_file():
        raise DeliveryQaError('DWM-evidensfil mangler: ' + relative)
    return target


def _binding(work: str | Path, depot_rel: str, depot: dict,
             job_uid: str = '') -> dict | None:
    """Bind only the exact a9/a10 report sibling files to the chosen depot run."""
    report = depot.get('delivery_validation')
    if report is None:
        return None
    if not isinstance(report, dict) or report.get('model_id') not in MODEL_IDS:
        raise DeliveryQaError('Ukjent DWM-avleveringsmodell i depotrapport')
    state = str(report.get('status') or '')
    if state == 'not_assessed' and report.get('complete') is False:
        return {'status': state, 'complete': False, 'count': 0,
                'version': report.get('version'), 'reason': report.get('reason') or ''}
    if (not state.startswith('completed_') or report.get('complete') is not True
            or report.get('version') not in VERSIONS
            or report.get('automatic_approval') is not False):
        raise DeliveryQaError('Ufullstendig eller ukjent DWM-avleveringsrapport')
    count = report.get('finding_count')
    errs = report.get('delivery_value_findings')
    periods = report.get('period_review_findings') or 0
    if (type(count) is not int or count < 0 or type(errs) is not int or errs < 0
            or type(periods) is not int or periods < 0 or count != errs + periods):
        raise DeliveryQaError('Motstridende antall DWM-avleveringsfunn')
    for key in ('finding_file_sha256', 'finding_csv_sha256', 'source_sha256'):
        if not isinstance(report.get(key), str) or not _SHA.fullmatch(report[key]):
            raise DeliveryQaError('Manglende SHA-256 i DWM-avleveringsrapport: ' + key)
    if (not isinstance(depot_rel, str) or '\\' in depot_rel or
            not depot_rel.startswith('noark5_reports/depot_validation/') or
            not depot_rel.endswith('/depot_validation_report.json')):
        raise DeliveryQaError('Ukjent depotrapportsti ved binding av avleveringsfunn')
    relative_dir = depot_rel.rsplit('/', 1)[0]
    jsonl_rel = relative_dir + '/delivery-funn.jsonl'
    csv_rel = relative_dir + '/delivery-funn.csv'
    if (report.get('finding_file') != 'delivery-funn.jsonl' or
            report.get('finding_csv') != 'delivery-funn.csv' or
            report.get('findings_relative') != jsonl_rel):
        raise DeliveryQaError('DWM-funn er ikke knyttet til valgt depotrapport')
    root = Path(work).resolve(strict=True)
    jsonl = _safe_work_file(root, jsonl_rel)
    csv = _safe_work_file(root, csv_rel)
    # Do not conflate the Work file hash with original Source XML identity.
    # A10 has already hashed Source during the actual read-only XML scan.
    manifest_rel = relative_dir + '/artifact_manifest.json'
    manifest_file = root / manifest_rel
    if manifest_file.is_file() or manifest_file.is_symlink():
        manifest_file = _safe_work_file(root, manifest_rel)
        if manifest_file.stat().st_size > 1024 * 1024:
            raise DeliveryQaError('DWM-artefaktmanifest er uventet stort')
        try:
            manifest = json.loads(manifest_file.read_text(encoding='utf-8'))
        except (OSError, ValueError, UnicodeError) as exc:
            raise DeliveryQaError('Uleselig DWM-artefaktmanifest') from exc
        if (manifest.get('operation_id') != 'build_noark5_depot_report' or
                (job_uid and manifest.get('job_uid') and manifest['job_uid'] != job_uid)):
            raise DeliveryQaError('DWM-avleveringsfunn tilhører en annen Work-jobb')
    source_counts = {}
    for rule in report.get('rules') or ():
        if not isinstance(rule, dict) or rule.get('metadata_id') not in ('M051','M052','M053','M054'):
            raise DeliveryQaError('Ukjent regelstatus i DWM-avleveringsrapport')
        mid = rule['metadata_id']
        n = rule.get('delivery_deviations')
        if mid in source_counts or type(n) is not int or n < 0:
            raise DeliveryQaError('Ugyldig eller duplisert avleveringsregelstatus')
        source_counts[mid] = n
    if len(source_counts) != 4 or sum(source_counts.values()) != errs:
        raise DeliveryQaError('Antall DWM-regelavvik stemmer ikke med depotrapport')
    return {'status': state, 'complete': True, 'count': count,
            'value_findings': errs, 'period_findings': periods,
            'source_counts': source_counts, 'version': report['version'],
            'job_uid': job_uid, 'jsonl_relative': jsonl_rel,
            'csv_relative': csv_rel, 'jsonl_path': jsonl, 'csv_path': csv,
            'jsonl_sha256': report['finding_file_sha256'],
            'csv_sha256': report['finding_csv_sha256'],
            'source_xml_sha256': report['source_sha256'],
            'source_reference': report.get('source_reference') or {},
            'depot_relative': depot_rel}


def _project(raw: dict, binding: dict) -> dict:
    """Preserve the source outcome and make the established QA key occurrence-unique."""
    if not isinstance(raw, dict) or any(k not in raw for k in _REQUIRED):
        raise DeliveryQaError('Ufullstendig DWM-avleveringsforekomst')
    src = raw['source']
    mid = raw['metadata_id']
    if src == 'DWM avleveringskontroll':
        if (mid not in binding['source_counts'] or
                raw['test_id'] != 'DWM-AVLEVERING-' + mid or
                raw['severity'] != 'ERROR' or raw.get('delivery_value') is not False or
                type(raw.get('standard_value')) is not bool):
            raise DeliveryQaError('Feil klassifisering av DWM-avleveringsfunn')
    elif src == 'DWM periodekonsistens':
        if (mid != 'M107/M108' or raw['test_id'] != 'DWM-PERIODE-M107-M108' or
                raw['severity'] != 'REVIEW'):
            raise DeliveryQaError('Feil klassifisering av periodeobservasjon')
    else:
        raise DeliveryQaError('Ukjent DWM-avleveringskilde')
    uid = raw.get('finding_uid')
    if not isinstance(uid, str) or not _SHA.fullmatch(uid):
        raise DeliveryQaError('DWM-funnet mangler unik kilde-ID')
    if raw.get('source_ref') != binding['jsonl_relative'] or raw.get('file') != 'arkivstruktur.xml':
        raise DeliveryQaError('DWM-funn viser til annen kilde enn depotrapport')
    if not isinstance(raw.get('message'), str) or not raw['message']:
        raise DeliveryQaError('DWM-funn mangler opprinnelig melding')
    if (not isinstance(raw.get('xpath'), str) or not raw['xpath'] or
            not isinstance(raw.get('context'), str) or
            not all(isinstance(raw.get(k), str) for k in ('object_id','archive_part_id')) or
            not isinstance(raw.get('lines'), list) or
            any(type(n) is not int or n < 1 for n in raw['lines']) or
            raw.get('requires_review') is not True):
        raise DeliveryQaError('DWM-funn mangler sikker XML- eller vurderingsreferanse')
    row = dict(raw)
    # a13 uses a canonical fingerprint of context rather than finding_uid.
    # Include the unique source UID to prevent same-line identical occurrences
    # from sharing one professional decision accidentally.
    # Also expose the original XPath and object/part IDs in the EXISTING
    # KS review field and A260 CSV context (JSONL retains separate fields).
    # No XPath is executed or newly inferred from a line reference here.
    trace = [raw['context'], 'XPath: ' + raw['xpath']]
    if raw['object_id']:
        trace.append('Objekt-ID: ' + raw['object_id'])
    if raw['archive_part_id']:
        trace.append('Arkivdel-ID: ' + raw['archive_part_id'])
    trace.append('Forekomst-ID: ' + uid)
    row['context'] = ' | '.join(part for part in trace if part)
    row['source_xml_sha256'] = binding['source_xml_sha256']
    row['noark_version'] = binding['version']
    row['evidence_role'] = 'original_dwm_delivery_observation_not_depot_approval'
    return row


def iter_verified_delivery(work: str | Path, depot_rel: str, depot: dict,
                           *, job_uid: str = '') -> Iterator[dict]:
    """Read every DWM observation. SHA and totals are verified at EOF.

    Consumers MUST finish the generator before publishing an export. A260
    stages its output, so a late mismatch never publishes a partial register.
    """
    binding = _binding(work, depot_rel, depot, job_uid)
    if binding is None or not binding.get('complete'):
        return
    counts: Counter[str] = Counter()
    period_count = 0
    total = 0
    digest = sha256()
    try:
        with binding['jsonl_path'].open('rb') as stream:
            while True:
                line = stream.readline(MAX_FINDING_LINE_BYTES + 1)
                if not line:
                    break
                if len(line) > MAX_FINDING_LINE_BYTES:
                    raise DeliveryQaError('Én DWM-funnpost er for stor (ingen avkorting)')
                digest.update(line)
                try:
                    raw = json.loads(line)
                except (ValueError, UnicodeError) as exc:
                    raise DeliveryQaError('Ugyldig DWM-funnpost i JSONL') from exc
                row = _project(raw, binding)
                total += 1
                if row['source'] == 'DWM periodekonsistens':
                    period_count += 1
                else:
                    counts[row['metadata_id']] += 1
                if total > binding['count']:
                    raise DeliveryQaError('Flere DWM-funn enn det depotrapporten dokumenterer')
                yield row
    except OSError as exc:
        raise DeliveryQaError('Kan ikke lese DWM-avleveringsfunn') from exc
    if digest.hexdigest() != binding['jsonl_sha256']:
        raise DeliveryQaError('SHA-256-avvik i komplett DWM-funnregister')
    if total != binding['count'] or period_count != binding['period_findings'] or dict(counts) != {
            k: v for k, v in binding['source_counts'].items() if v}:
        raise DeliveryQaError('DWM-funnregisteret stemmer ikke med depotrapportens oppsummering')
    if _hash(binding['csv_path']) != binding['csv_sha256']:
        raise DeliveryQaError('SHA-256-avvik i DWM-funnregisterets CSV-evidens')


def delivery_for_snapshot(work: str | Path, depot_rel: str, depot: dict, *,
                          job_uid: str = '', preview_limit: int = PREVIEW_LIMIT) -> dict:
    """Complete inline source for ordinary jobs; explicitly partial for large jobs.

    All source lines are checked even if only the first preview_limit rows are
    returned to the in-memory KS UI. Full register remains in original Work.
    """
    if type(preview_limit) is not int or not 0 <= preview_limit <= 5000:
        raise DeliveryQaError('Ugyldig KS-forhåndsvisningsstørrelse')
    b = _binding(work, depot_rel, depot, job_uid)
    if b is None:
        return {'status': 'not_available', 'findings': [], 'finding_count': 0,
                'findings_complete': True, 'source': None, 'evidence': []}
    if not b['complete']:
        return {'status': 'not_assessed', 'reason': b.get('reason') or '',
                'findings': [], 'finding_count': 0, 'findings_complete': True,
                'source': None, 'evidence': []}
    findings: list[dict] = []
    for row in iter_verified_delivery(work, depot_rel, depot, job_uid=job_uid):
        if len(findings) < preview_limit:
            findings.append(row)
    evidence = [
        {'kind': 'dwm_delivery_findings', 'path': b['jsonl_relative'],
         'state': 'sha256_verified', 'sha256': b['jsonl_sha256'],
         'bytes': b['jsonl_path'].stat().st_size},
        {'kind': 'dwm_delivery_csv', 'path': b['csv_relative'],
         'state': 'sha256_verified', 'sha256': b['csv_sha256'],
         'bytes': b['csv_path'].stat().st_size},
    ]
    return {'status': b['status'], 'source': b['jsonl_relative'],
            'source_sha256': b['source_xml_sha256'], 'noark_version': b['version'],
            'finding_count': b['count'], 'findings': findings,
            'findings_complete': b['count'] == len(findings),
            'evidence': evidence,
            'note': ('Alle DWM-funn er verifisert, men KS viser bare en forhåndsvisning.'
                     if b['count'] > len(findings) else
                     'Samtlige DWM-funn er tilgjengelige for individuell faglig vurdering.'),
            'automatic_approval': False}


def page_delivery_findings(work: str | Path, depot_rel: str, depot: dict, *,
                           job_uid: str = '', offset: int = 0,
                           page_size: int = 200, severity: str = '') -> dict:
    """Bounded-memory page reader; a12 will add indexed GUI navigation."""
    if (type(offset) is not int or offset < 0 or type(page_size) is not int
            or not 1 <= page_size <= 1000 or severity not in ('', 'ERROR', 'REVIEW')):
        raise DeliveryQaError('Ugyldig sideutvalg for DWM-funn')
    data = []
    total = 0
    for row in iter_verified_delivery(work, depot_rel, depot, job_uid=job_uid):
        if severity and row['severity'] != severity:
            continue
        if offset <= total < offset + page_size:
            data.append(row)
        total += 1
    return {'offset': offset, 'page_size': page_size,
            'total': total, 'rows': data, 'complete': True}


def attach_delivery_to_snapshot(work: str | Path, snapshot: dict) -> dict:
    """Make every original DWM observation reviewable in the established a13 KS.

    The original a9/a10 status remains in the immutable depot report; aggregate
    report deviations are removed only when corresponding individual evidence
    is present and fully verified. Both canonical and saved-Work builders enter
    this same bridge. Large results remain a verified preview until a12 GUI.
    """
    root = Path(work).resolve(strict=True)
    manifests = [entry for entry in snapshot.get('evidence_manifest') or []
                 if entry.get('kind') == 'dwm_depot']
    if len(manifests) != 1:
        raise DeliveryQaError('KS mangler entydig depotrapport for DWM-avleveringsfunn')
    depot_row = manifests[0]
    depot_rel = depot_row.get('path')
    depot_path = _safe_work_file(root, depot_rel)
    depot_digest = _hash(depot_path)
    if depot_digest != depot_row.get('sha256'):
        raise DeliveryQaError('KS-depotrapporten er endret siden KS-grunnlaget ble lest')
    if depot_path.stat().st_size > 24 * 1024 * 1024:
        # A18: full a17 streaming projection retains the small a9/a10
        # delivery-validation manifest; it does not copy giant XPath details.
        from .qa_depot_stream_v023_a17 import project_depot_report
        depot, parsed_digest = project_depot_report(depot_path)
        if parsed_digest != depot_digest:
            raise DeliveryQaError('Depotrapporten ble endret mellom lesinger')
    else:
        try:
            depot = json.loads(depot_path.read_text(encoding='utf-8-sig'))
        except (OSError, ValueError, UnicodeError) as exc:
            raise DeliveryQaError('KS-depotrapport kan ikke leses') from exc
    if not isinstance(depot, dict) or depot.get('report_type') != 'noark5_depot_validation':
        raise DeliveryQaError('KS har ikke valgt en gjenkjent DWM-depotrapport')
    uid = str((snapshot.get('work_identity') or {}).get('job_uid') or '')
    if not uid:
        raise DeliveryQaError('KS mangler identitet for valgt Work-jobb')
    delivery = delivery_for_snapshot(root, depot_rel, depot, job_uid=uid)
    if delivery['status'] == 'not_available':
        return snapshot
    enriched = dict(snapshot)
    if delivery['status'] == 'not_assessed':
        enriched['delivery_qa'] = {'status': 'not_assessed',
                                   'reason': delivery.get('reason') or '',
                                   'automatic_approval': False}
        return enriched
    originals = list(snapshot.get('findings') or ())
    kept = [item for item in originals if not (
        item.get('source') == 'DWM depotvalidering' and
        item.get('test_id') in AGGREGATE_CATEGORIES)]
    dropped = len(originals) - len(kept)
    keys = set()
    for row in kept:
        from .qa_review_v021_a13 import finding_key
        keys.add(finding_key(row))
    for row in delivery['findings']:
        from .qa_review_v021_a13 import finding_key
        key = finding_key(row)
        if key in keys:
            raise DeliveryQaError('Kolliderende individuelle DWM-avleveringsfunn')
        keys.add(key)
        kept.append(row)
    existing_count = snapshot.get('full_finding_count')
    if type(existing_count) is not int or existing_count < len(originals):
        existing_count = len(originals)
    enriched['findings'] = kept
    enriched['full_finding_count'] = existing_count - dropped + delivery['finding_count']
    enriched['findings_complete'] = (bool(snapshot.get('findings_complete', True))
                                      and delivery['findings_complete'])
    enriched['delivery_qa'] = {k: v for k, v in delivery.items() if k not in ('findings', 'evidence')}
    enriched['evidence_manifest'] = list(snapshot.get('evidence_manifest') or []) + delivery['evidence']
    if not enriched['findings_complete']:
        enriched['report_status'] = 'DRAFT_PARTIAL_PREVIEW_NOT_FOR_PUBLICATION'
        enriched['limitations'] = list(snapshot.get('limitations') or []) + [
            'KS inneholder kun forhåndsvisning av DWM-avleveringsfunn. '
            'Hele kildeverifiserte registeret finnes i Work og A260. '
            'Komplett KS-eksport er sperret til sidevis behandling er implementert.'
        ]
    return enriched
